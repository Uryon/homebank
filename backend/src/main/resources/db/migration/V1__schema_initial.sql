-- Schéma de référence de HomeBank, tel que Hibernate le créait jusqu'ici
-- (ddl-auto=update). Exécuté seulement sur une base vide : une base existante
-- est enregistrée directement en version 1 sans rien exécuter
-- (spring.flyway.baseline-on-migrate, voir application.properties).
-- SQL commun à PostgreSQL et à H2 en mode PostgreSQL (profil test). Les noms
-- des clés étrangères reprennent ceux générés par Hibernate, pour qu'une
-- migration ultérieure puisse les désigner sur toutes les bases.

create table comptes (
    id bigint generated by default as identity primary key,
    archived boolean not null,
    currency varchar(3) not null,
    initial_balance numeric(19, 2) not null,
    name varchar(255) not null,
    notes varchar(255),
    type varchar(255) not null,
    constraint comptes_type_check check (type in ('CHECKING', 'SAVINGS', 'CASH', 'CREDIT_CARD', 'INVESTMENT'))
);

create table categories (
    id bigint generated by default as identity primary key,
    annualized boolean default false not null,
    hidden boolean default false not null,
    icon varchar(255),
    name varchar(255) not null,
    type varchar(255) not null,
    parent_id bigint,
    constraint categories_type_check check (type in ('INCOME', 'EXPENSE', 'BOTH')),
    constraint fksaok720gsu4u2wrgbk10b5n8d foreign key (parent_id) references categories (id)
);

create table tiers (
    id bigint generated by default as identity primary key,
    amount numeric(19, 2),
    name varchar(255) not null,
    pattern text not null,
    category_id bigint,
    constraint fkmxi6eynp8abamyo8uo8y4vmgb foreign key (category_id) references categories (id)
);

create table transactions (
    id bigint generated by default as identity primary key,
    amount numeric(19, 2) not null,
    balance_adjustment boolean default false not null,
    bank_label varchar(500),
    date date not null,
    duplicate_ignored boolean default false not null,
    exceptional boolean default false not null,
    memo varchar(255),
    payment_mode varchar(255) not null,
    monthly_expense boolean not null,
    periodic_suggestion_ignored boolean default false not null,
    split_from_amount numeric(19, 2),
    validated boolean not null,
    account_id bigint not null,
    category_id bigint,
    payee_id bigint,
    transfer_transaction_id bigint,
    constraint transactions_payment_mode_check check (payment_mode in ('NONE', 'CREDIT_CARD', 'CHEQUE', 'CASH', 'TRANSFER',
        'DIRECT_DEBIT', 'STANDING_ORDER', 'ELECTRONIC_PAYMENT', 'DEPOSIT', 'CARD')),
    constraint fkpmupggcs0l5x69ven5vu9sc0x foreign key (account_id) references comptes (id),
    constraint fksqqi7sneo04kast0o138h19mv foreign key (category_id) references categories (id),
    constraint fkptn57guv4kgfnyqidgjm89reh foreign key (payee_id) references tiers (id),
    constraint fknsuclwb5uc6th4jijmvda7bvs foreign key (transfer_transaction_id) references transactions (id)
);

create index idx_transactions_compte_date on transactions (account_id, date);
create index idx_transactions_date on transactions (date);
create index idx_transactions_tiers on transactions (payee_id);
create index idx_transactions_categorie on transactions (category_id);
create index idx_transactions_virement on transactions (transfer_transaction_id);

create table transactions_supprimees (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    amount numeric(19, 2) not null,
    bank_label varchar(500),
    date date not null,
    deleted_at date not null,
    payee_name varchar(255)
);

create index idx_transactions_supprimees_compte on transactions_supprimees (account_id);

create table prets (
    id bigint generated by default as identity primary key,
    annual_rate numeric(6, 3) not null,
    monthly_insurance numeric(19, 2),
    monthly_payment numeric(19, 2) not null,
    name varchar(255) not null,
    notes varchar(255),
    principal numeric(19, 2) not null,
    start_date date not null,
    term_months integer not null
);

-- Une seule ligne, d'id fixe (voir DernierImport) : pas d'identité.
create table dernier_import (
    id bigint primary key,
    date_heure timestamp(6) not null
);
