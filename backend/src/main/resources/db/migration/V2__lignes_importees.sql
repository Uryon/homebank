-- Registre des lignes de releve deja importees (voir LigneImportee) : une
-- ligne enregistree ici n'est plus jamais reimportee, quoi que soit devenue
-- sa transaction depuis (tiers change, divisee, supprimee...).
create table lignes_importees (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    date date not null,
    amount numeric(19, 2) not null,
    label varchar(500) not null,
    transaction_id bigint
);

create index idx_lignes_importees_compte on lignes_importees (account_id);
create index idx_lignes_importees_transaction on lignes_importees (transaction_id);

-- Reprise de l'existant : transactions importees (libelle bancaire conserve),
-- au montant du releve (celui d'avant division le cas echeant)...
insert into lignes_importees (account_id, date, amount, label, transaction_id)
select account_id, date, coalesce(split_from_amount, amount), bank_label, id
from transactions
where bank_label is not null and bank_label <> '';

-- ... et transactions supprimees depuis. Avant le libelle bancaire, une ligne
-- importee n'etait memorisee que par le nom de son tiers, cree a partir du
-- libelle brut : c'est ce nom qui est repris.
insert into lignes_importees (account_id, date, amount, label, transaction_id)
select account_id, date, amount, coalesce(nullif(bank_label, ''), payee_name), null
from transactions_supprimees
where coalesce(nullif(bank_label, ''), payee_name) is not null
  and coalesce(nullif(bank_label, ''), payee_name) <> '';
